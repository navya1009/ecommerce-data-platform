#!/bin/bash
# scripts/bootstrap_spark_worker.sh
# -----------------------------------------------------------------------------
# Bootstrap script for Spark worker EC2 instances (launched by ASG).
# Installs Java 11 + Spark 3.5.0, then starts the worker service via systemd.
# -----------------------------------------------------------------------------

set -euo pipefail

exec > >(tee -a /var/log/bootstrap_spark_worker.log) 2>&1

echo "=============================================="
echo "Starting Spark worker bootstrap: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "=============================================="

SPARK_VERSION="3.5.0"
HADOOP_VERSION="3"
SPARK_HOME="/opt/spark"
SPARK_MASTER_URL="${SPARK_MASTER_URL}"

# -----------------------------------------------------------------------------
# 1. Install Java 11
# -----------------------------------------------------------------------------
if ! command -v java &>/dev/null; then
    echo "[1/5] Installing Java 11..."
    dnf install -y java-11-amazon-corretto-headless wget tar
else
    echo "[1/5] Java already installed."
fi

# -----------------------------------------------------------------------------
# 2. Download and install Spark
# -----------------------------------------------------------------------------
if [ ! -d "$SPARK_HOME" ]; then
    echo "[2/5] Downloading Spark $SPARK_VERSION..."
    cd /opt
    wget -q "https://archive.apache.org/dist/spark/spark-$${SPARK_VERSION}/spark-$${SPARK_VERSION}-bin-hadoop$${HADOOP_VERSION}.tgz"
    tar -xzf "spark-$${SPARK_VERSION}-bin-hadoop$${HADOOP_VERSION}.tgz"
    mv "spark-$${SPARK_VERSION}-bin-hadoop$${HADOOP_VERSION}" spark
    rm -f "spark-$${SPARK_VERSION}-bin-hadoop$${HADOOP_VERSION}.tgz"
else
    echo "[2/5] Spark already installed at $SPARK_HOME"
fi

# -----------------------------------------------------------------------------
# 3. Download JDBC drivers
# -----------------------------------------------------------------------------
echo "[3/5] Installing JDBC drivers..."
JARS_DIR="$SPARK_HOME/jars"

if [ ! -f "$JARS_DIR/mysql-connector-java-8.0.33.jar" ]; then
    wget -q "https://repo1.maven.org/maven2/mysql/mysql-connector-java/8.0.33/mysql-connector-java-8.0.33.jar" \
        -O "$JARS_DIR/mysql-connector-java-8.0.33.jar"
fi

if [ ! -f "$JARS_DIR/postgresql-42.6.0.jar" ]; then
    wget -q "https://jdbc.postgresql.org/download/postgresql-42.6.0.jar" \
        -O "$JARS_DIR/postgresql-42.6.0.jar"
fi

# -----------------------------------------------------------------------------
# 4. Configure spark-defaults.conf
# -----------------------------------------------------------------------------
echo "[4/5] Writing spark-defaults.conf..."
cat > "$SPARK_HOME/conf/spark-defaults.conf" <<EOF
# Generated by bootstrap_spark_worker.sh
spark.master                        $${SPARK_MASTER_URL}
spark.worker.cores                  2
spark.worker.memory                 2g
spark.serializer                    org.apache.spark.serializer.JavaSerializer
spark.jars                          $${JARS_DIR}/mysql-connector-java-8.0.33.jar,$${JARS_DIR}/postgresql-42.6.0.jar
EOF

chown -R ec2-user:ec2-user "$SPARK_HOME"

# -----------------------------------------------------------------------------
# 5. Register Spark worker as systemd service and start it
# -----------------------------------------------------------------------------
echo "[5/5] Creating systemd unit for spark-worker..."
cat > /etc/systemd/system/spark-worker.service <<EOF
[Unit]
Description=Apache Spark Worker
After=network.target

[Service]
Type=forking
User=ec2-user
Group=ec2-user
Environment="SPARK_HOME=$${SPARK_HOME}"
Environment="JAVA_HOME=$(dirname $(dirname $(readlink -f $(which java))))"
ExecStart=$${SPARK_HOME}/sbin/start-worker.sh $${SPARK_MASTER_URL}
ExecStop=$${SPARK_HOME}/sbin/stop-worker.sh
Restart=on-failure
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable spark-worker
systemctl start spark-worker

echo "=============================================="
echo "Spark worker bootstrap complete: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "Connecting to master at: $${SPARK_MASTER_URL}"
echo "=============================================="