#!/bin/bash
# scripts/bootstrap_spark.sh
# -----------------------------------------------------------------------------
# Bootstrap script for the Spark master EC2 instance.
# Installs Java 11 + Spark 3.5.0, configures spark-defaults.conf, and
# starts the master service via systemd.
# -----------------------------------------------------------------------------

set -euo pipefail

exec > >(tee -a /var/log/bootstrap_spark.log) 2>&1

echo "=============================================="
echo "Starting Spark bootstrap: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "=============================================="

SPARK_VERSION="3.5.0"
HADOOP_VERSION="3"
SPARK_HOME="/opt/spark"
S3_BUCKET="${S3_BUCKET}"
SPARK_MASTER_HOST="$(hostname -I | awk '{print $1}')"

# -----------------------------------------------------------------------------
# 1. Install Java 11
# -----------------------------------------------------------------------------
if ! command -v java &>/dev/null; then
    echo "[1/6] Installing Java 11..."
    dnf install -y java-11-amazon-corretto-headless wget tar
else
    echo "[1/6] Java already installed: $(java -version 2>&1 | head -1)"
fi

# -----------------------------------------------------------------------------
# 2. Download and install Spark
# -----------------------------------------------------------------------------
if [ ! -d "$SPARK_HOME" ]; then
    echo "[2/6] Downloading Spark $SPARK_VERSION..."
    cd /opt
    wget -q "https://archive.apache.org/dist/spark/spark-$${SPARK_VERSION}/spark-$${SPARK_VERSION}-bin-hadoop$${HADOOP_VERSION}.tgz"
    tar -xzf "spark-$${SPARK_VERSION}-bin-hadoop$${HADOOP_VERSION}.tgz"
    mv "spark-$${SPARK_VERSION}-bin-hadoop$${HADOOP_VERSION}" spark
    rm -f "spark-$${SPARK_VERSION}-bin-hadoop$${HADOOP_VERSION}.tgz"
else
    echo "[2/6] Spark already installed at $SPARK_HOME"
fi

# -----------------------------------------------------------------------------
# 3. Download JDBC drivers
# -----------------------------------------------------------------------------
echo "[3/6] Installing JDBC drivers..."
JARS_DIR="$SPARK_HOME/jars"

if [ ! -f "$JARS_DIR/mysql-connector-java-8.0.33.jar" ]; then
    wget -q "https://repo1.maven.org/maven2/mysql/mysql-connector-java/8.0.33/mysql-connector-java-8.0.33.jar" \
        -O "$JARS_DIR/mysql-connector-java-8.0.33.jar"
fi

if [ ! -f "$JARS_DIR/postgresql-42.6.0.jar" ]; then
    wget -q "https://jdbc.postgresql.org/download/postgresql-42.6.0.jar" \
        -O "$JARS_DIR/postgresql-42.6.0.jar"
fi

# -----------------------------------------------------------------------------
# 4. Configure spark-defaults.conf
# -----------------------------------------------------------------------------
echo "[4/6] Writing spark-defaults.conf..."
cat > "$SPARK_HOME/conf/spark-defaults.conf" <<EOF
# ----------------------------------------------------------------------------
# Spark defaults for ecommerce-data-platform
# Generated by bootstrap_spark.sh — do not edit manually
# ----------------------------------------------------------------------------

spark.master                        spark://$${SPARK_MASTER_HOST}:7077
spark.eventLog.enabled              true
spark.eventLog.dir                  s3a://${S3_BUCKET}/spark-events/
spark.history.fs.logDirectory       s3a://${S3_BUCKET}/spark-events/

# Dynamic allocation
spark.dynamicAllocation.enabled     true
spark.dynamicAllocation.minExecutors 1
spark.dynamicAllocation.maxExecutors 4
spark.dynamicAllocation.initialExecutors 2

# S3A filesystem (requires hadoop-aws + aws-java-sdk on the classpath)
spark.hadoop.fs.s3a.impl            org.apache.hadoop.fs.s3a.S3AFileSystem
spark.hadoop.fs.s3a.aws.credentials.provider \
    com.amazonaws.auth.DefaultAWSCredentialsProviderChain
spark.hadoop.fs.s3a.endpoint        s3.amazonaws.com

# JDBC
spark.jars                          $${JARS_DIR}/mysql-connector-java-8.0.33.jar,$${JARS_DIR}/postgresql-42.6.0.jar

# Serializer
spark.serializer                    org.apache.spark.serializer.JavaSerializer

# Logging
spark.log.level                     WARN
EOF

# -----------------------------------------------------------------------------
# 5. Register Spark master as a systemd service
# -----------------------------------------------------------------------------
echo "[5/6] Creating systemd unit for spark-master..."
cat > /etc/systemd/system/spark-master.service <<EOF
[Unit]
Description=Apache Spark Master
After=network.target

[Service]
Type=forking
User=ec2-user
Group=ec2-user
Environment="SPARK_HOME=$${SPARK_HOME}"
Environment="JAVA_HOME=$(dirname $(dirname $(readlink -f $(which java))))"
ExecStart=$${SPARK_HOME}/sbin/start-master.sh
ExecStop=$${SPARK_HOME}/sbin/stop-master.sh
Restart=on-failure
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable spark-master
systemctl start spark-master

# Also register worker unit (ready for scaling via ASG user_data later)
cat > /etc/systemd/system/spark-worker.service <<EOF
[Unit]
Description=Apache Spark Worker
After=network.target spark-master.service

[Service]
Type=forking
User=ec2-user
Group=ec2-user
Environment="SPARK_HOME=$${SPARK_HOME}"
Environment="JAVA_HOME=$(dirname $(dirname $(readlink -f $(which java))))"
ExecStart=$${SPARK_HOME}/sbin/start-worker.sh spark://$${SPARK_MASTER_HOST}:7077
ExecStop=$${SPARK_HOME}/sbin/stop-worker.sh
Restart=on-failure
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable spark-worker

chown -R ec2-user:ec2-user "$SPARK_HOME"

# -----------------------------------------------------------------------------
# 6. Ship logs to CloudWatch
# -----------------------------------------------------------------------------
echo "[6/6] Configuring CloudWatch agent..."
dnf install -y amazon-cloudwatch-agent

cat > /opt/aws/amazon-cloudwatch-agent/etc/amazon-cloudwatch-agent.json <<EOF
{
  "logs": {
    "logs_collected": {
      "files": {
        "collect_list": [
          {
            "file_path": "$${SPARK_HOME}/logs/*.out",
            "log_group_name": "/aws/ec2/ecommerce-data-platform-${ENVIRONMENT}/spark",
            "log_stream_name": "{instance_id}/spark-master",
            "timezone": "UTC"
          },
          {
            "file_path": "/var/log/bootstrap_spark.log",
            "log_group_name": "/aws/ec2/ecommerce-data-platform-${ENVIRONMENT}/spark",
            "log_stream_name": "{instance_id}/bootstrap",
            "timezone": "UTC"
          }
        ]
      }
    }
  }
}
EOF

/opt/aws/amazon-cloudwatch-agent/bin/amazon-cloudwatch-agent-ctl \
    -a fetch-config \
    -m ec2 \
    -c file:/opt/aws/amazon-cloudwatch-agent/etc/amazon-cloudwatch-agent.json \
    -s

systemctl enable amazon-cloudwatch-agent

echo "=============================================="
echo "Spark bootstrap complete: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "Spark master should be reachable at spark://$${SPARK_MASTER_HOST}:7077"
echo "=============================================="